// ข้อมูลสมมติสำหรับโหมดสาธิต — ไม่ใช่ข้อมูลจริง
// รายชื่อโรงเรียนเป็นชื่อสมมติ รายการกีฬาเป็นร่างเพื่อให้ฝ่ายเทคนิคกีฬาตรวจแก้
(function () {
  const districts = [
    'เมืองชัยภูมิ', 'บ้านเขว้า', 'คอนสวรรค์', 'เกษตรสมบูรณ์', 'หนองบัวแดง',
    'จัตุรัส', 'บำเหน็จณรงค์', 'หนองบัวระเหว', 'เทพสถิต', 'ภูเขียว',
    'บ้านแท่น', 'แก้งคร้อ', 'คอนสาร', 'ภักดีชุมพล', 'เนินสง่า', 'ซับใหญ่',
  ];

  // 2 โรงเรียนสมมติต่ออำเภอ (อ.เมือง 4 โรง) = 34 โรง
  const schools = [];
  let n = 1;
  districts.forEach((d) => {
    const count = d === 'เมืองชัยภูมิ' ? 4 : 2;
    for (let i = 1; i <= count; i++) {
      const code = 'CYP' + String(n).padStart(3, '0');
      schools.push({ code, name: `โรงเรียนตัวอย่าง${d} ${i}`, district: d });
      n++;
    }
  });

  // รุ่นอายุกำหนดตามชนิดกีฬา (ตามมติ: แต่ละกีฬากำหนดรุ่นเอง)
  const sportsDef = [
    { id: 'football', name: 'ฟุตบอล', kind: 'ทีม', items: [
      ['ทีม', 'ชาย', ['14 ปี', '16 ปี', '18 ปี']],
      ['ทีม', 'หญิง', ['16 ปี']],
    ]},
    { id: 'futsal', name: 'ฟุตซอล', kind: 'ทีม', items: [
      ['ทีม', 'ชาย', ['14 ปี', '16 ปี', '18 ปี']],
      ['ทีม', 'หญิง', ['16 ปี', '18 ปี']],
    ]},
    { id: 'volleyball', name: 'วอลเลย์บอล', kind: 'ทีม', items: [
      ['ทีม', 'ชาย', ['14 ปี', '16 ปี', '18 ปี']],
      ['ทีม', 'หญิง', ['14 ปี', '16 ปี', '18 ปี']],
    ]},
    { id: 'basketball', name: 'บาสเกตบอล', kind: 'ทีม', items: [
      ['ทีม', 'ชาย', ['16 ปี', '18 ปี']],
      ['ทีม', 'หญิง', ['16 ปี', '18 ปี']],
    ]},
    { id: 'takraw', name: 'เซปักตะกร้อ', kind: 'ทีม', items: [
      ['ทีมเดี่ยว', 'ชาย', ['14 ปี', '16 ปี', '18 ปี']],
      ['ทีมเดี่ยว', 'หญิง', ['16 ปี']],
    ]},
    { id: 'petanque', name: 'เปตอง', kind: 'บุคคล/ทีม', items: [
      ['เดี่ยว', 'ชาย', ['ม.ต้น', 'ม.ปลาย']],
      ['เดี่ยว', 'หญิง', ['ม.ต้น', 'ม.ปลาย']],
      ['ทีม 3 คน', 'ชาย', ['ม.ต้น', 'ม.ปลาย']],
      ['ทีม 3 คน', 'หญิง', ['ม.ต้น', 'ม.ปลาย']],
    ]},
    { id: 'badminton', name: 'แบดมินตัน', kind: 'บุคคล', items: [
      ['เดี่ยว', 'ชาย', ['15 ปี', '18 ปี']],
      ['เดี่ยว', 'หญิง', ['15 ปี', '18 ปี']],
      ['คู่', 'ชาย', ['18 ปี']],
      ['คู่', 'หญิง', ['18 ปี']],
      ['คู่ผสม', 'ผสม', ['18 ปี']],
    ]},
    { id: 'tabletennis', name: 'เทเบิลเทนนิส', kind: 'บุคคล', items: [
      ['เดี่ยว', 'ชาย', ['15 ปี', '18 ปี']],
      ['เดี่ยว', 'หญิง', ['15 ปี', '18 ปี']],
      ['ทีม', 'ชาย', ['18 ปี']],
      ['ทีม', 'หญิง', ['18 ปี']],
    ]},
    { id: 'athletics', name: 'กรีฑา', kind: 'บุคคล', items: [
      ['วิ่ง 100 ม.', 'ชาย', ['14 ปี', '16 ปี', '18 ปี']],
      ['วิ่ง 100 ม.', 'หญิง', ['14 ปี', '16 ปี', '18 ปี']],
      ['วิ่ง 400 ม.', 'ชาย', ['16 ปี', '18 ปี']],
      ['วิ่ง 400 ม.', 'หญิง', ['16 ปี', '18 ปี']],
      ['วิ่งผลัด 4x100 ม.', 'ชาย', ['14 ปี', '16 ปี', '18 ปี']],
      ['วิ่งผลัด 4x100 ม.', 'หญิง', ['14 ปี', '16 ปี', '18 ปี']],
      ['กระโดดไกล', 'ชาย', ['16 ปี', '18 ปี']],
      ['กระโดดไกล', 'หญิง', ['16 ปี', '18 ปี']],
      ['ทุ่มน้ำหนัก', 'ชาย', ['18 ปี']],
      ['ทุ่มน้ำหนัก', 'หญิง', ['18 ปี']],
    ]},
  ];

  const sports = sportsDef.map((s, i) => ({ id: s.id, name: s.name, kind: s.kind, sort: i + 1 }));
  const events = [];
  const genderCode = { 'ชาย': 'm', 'หญิง': 'f', 'ผสม': 'x' };
  sportsDef.forEach((s) => {
    s.items.forEach(([category, gender, divisions], ci) => {
      divisions.forEach((division) => {
        const divCode = division.replace(/[^0-9a-zA-Zก-๙]/g, '').replace('ปี', '').replace('ม.', '');
        events.push({
          id: `${s.id}-${ci}-${genderCode[gender]}-${divCode || division}`,
          sport_id: s.id,
          category,
          gender,
          division,
        });
      });
    });
  });

  // ตัวสุ่มแบบกำหนดค่าเริ่ม เพื่อให้ข้อมูลสมมติออกมาเหมือนเดิมทุกครั้ง
  function seeded(seed) {
    let s = seed >>> 0;
    return () => {
      s = (s * 1664525 + 1013904223) >>> 0;
      return s / 4294967296;
    };
  }

  // ความประสงค์สมมติ: ~80% ของโรงเรียนส่งแล้ว
  const rand = seeded(51);
  const popularity = { football: 0.32, futsal: 0.38, volleyball: 0.26, basketball: 0.1, takraw: 0.25,
    petanque: 0.18, badminton: 0.12, tabletennis: 0.06, athletics: 0.16 };
  const intents = [];
  const submittedAt = {};
  schools.forEach((sc, i) => {
    if (rand() < 0.2) return; // ยังไม่ส่ง
    const day = 1 + Math.floor(rand() * 8);
    submittedAt[sc.code] = `2026-11-${String(day).padStart(2, '0')}T09:00:00+07:00`;
    events.forEach((ev) => {
      if (rand() < popularity[ev.sport_id]) intents.push({ school_code: sc.code, event_id: ev.id });
    });
  });

  window.MOCK = { schools, sports, events, intents, submittedAt, DEMO_PIN: '111111' };
})();
